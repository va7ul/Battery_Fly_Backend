const { Schema, model } = require('mongoose');

// Хронологія роботи з клієнтом: дзвінки, зустрічі, листування, нотатки — і те,
// що система записала сама (замовлення, зміна стадії, засинання).
//
// ⚠️ ОКРЕМА колекція, а не масив усередині Contact. Записів у активного клієнта
// з часом десятки, і піддокументом вони їхали б у КОЖНІЙ відповіді зі списком
// клієнтів — сторінка на 50 осіб тягнула б за собою всю їхню переписку заради
// показу імені й телефону.
//
// ⚠️ Журнал НЕ редагується й не видаляється. Хронологія, яку можна підчистити,
// не варта нічого: менеджер має бачити, що насправді відбувалось, а не те, що
// хтось лишив після себе. Помилковий запис виправляється наступним записом.
const activitySchema = new Schema(
  {
    contactId: {
      type: Schema.Types.ObjectId,
      ref: 'contact',
      required: true,
      index: true,
    },
    type: {
      type: String,
      enum: ['call', 'meeting', 'message', 'note', 'system'],
      required: true,
    },
    text: { type: String, default: '', trim: true },
    // Коли це сталося. Окремо від createdAt: менеджер записує вчорашній дзвінок
    // сьогодні, і хронологія має стати на місце дзвінка, а не запису.
    date: { type: Date, default: Date.now, index: true },
    // Дата наступного контакту, домовлена САМЕ цим записом. Дублює поле
    // клієнта навмисно: у клієнта лежить лише актуальна дата, а тут видно, на
    // якому дзвінку про неї домовились.
    nextContactDate: { type: Date, default: null },
    // Логін менеджера. Рядком, а не посиланням: адмінів одиниці, а зв'язок
    // змусив би населяти його в кожному читанні журналу заради одного слова.
    createdBy: { type: String, default: '' },
    // Записала система чи людина. Видно в інтерфейсі: авто-подіям вірять
    // беззастережно, людським — рівно настільки, наскільки уважний був автор.
    isAuto: { type: Boolean, default: false },
  },
  { versionKey: false, timestamps: true }
);

// Хронологія завжди читається за клієнтом і від найсвіжішого.
activitySchema.index({ contactId: 1, date: -1 });

const Activity = model('activity', activitySchema);

module.exports = { Activity };

const { Schema, model } = require('mongoose');

// Замок фонової задачі: гарантія, що прохід іде в одному примірнику.
//
// ⚠️ Навіщо взагалі. Крон живе всередині веб-процесу, а процес на Render може
// бути не один — досить увімкнути другий інстанс або потрапити в момент
// деплою, коли старий ще живий, а новий уже стартував. Тоді два проходи
// одночасно надішлють менеджеру ДВА однакові сповіщення про повернення й
// подвоять записи в журналі. Замок у базі — єдине спільне місце, яке бачать усі
// примірники.
//
// ⚠️ `startedAt` тут не для звітності, а для страховки: якщо процес помер
// посеред проходу, знявши замок ніхто не встиг. Без позначки часу задача
// замовкла б назавжди, і ніхто б не помітив. Прострочений замок перехоплюється
// — див. helpers/cronLock.js.
const cronLockSchema = new Schema(
  {
    // Ім'я задачі. Воно ж _id: двох замків для однієї задачі бути не може, і
    // база стежить за цим сама.
    _id: { type: String },
    running: { type: Boolean, default: false },
    startedAt: { type: Date, default: null },
    finishedAt: { type: Date, default: null },
    // Короткий підсумок останнього проходу — щоб у базі було видно, чим
    // закінчилось, без копання в логах Render.
    lastResult: { type: String, default: '' },
  },
  { versionKey: false, timestamps: true, _id: false }
);

const CronLock = model('cronLock', cronLockSchema);

module.exports = { CronLock };

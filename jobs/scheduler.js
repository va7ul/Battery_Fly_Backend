const cron = require('node-cron');

const { runNpTracking } = require('./npTrackingJob');

// Щогодини з 7:00 до 21:00 за Києвом.
//
// ⚠️ timezone задано ЯВНО, а не взято з сервера. Render працює в UTC, і без
// цього рядка «сім ранку» настало б о десятій за Києвом, а взимку й влітку — у
// різний час. Це та сама причина, через яку в helpers/dashboard.js рахується
// київська доба, а не UTC-доба.
//
// ⚠️ Вночі не опитуємо свідомо. Пошта вночі майже не рухає посилки, а сенс
// трекінгу — щоб менеджер побачив повернення в робочий час, а не о третій ночі.
const РОЗКЛАД = '0 7-21 * * *';
const ЧАСОВИЙ_ПОЯС = 'Europe/Kyiv';

// ⚠️ Запускається з server.js, а НЕ з app.js. app.js імпортують тести й будь-які
// інструменти, що піднімають застосунок без мережі, — крон стартував би в
// кожному такому прогоні й ходив у Пошту з-під тестів.
function startScheduler() {
  if (!cron.validate(РОЗКЛАД)) {
    console.error('[scheduler] некоректний розклад:', РОЗКЛАД);

    return null;
  }

  const task = cron.schedule(
    РОЗКЛАД,
    () => {
      // Помилки прохід ковтає сам, але обіцянку «крон нічого не валить» тримаємо
      // й тут: невловлене відхилення в планувальнику поклало б увесь процес.
      runNpTracking().catch(error => {
        console.error('[scheduler] трекінг НП впав:', error.message);
      });
    },
    { timezone: ЧАСОВИЙ_ПОЯС }
  );

  console.info(
    `[scheduler] трекінг Нової Пошти: ${РОЗКЛАД} (${ЧАСОВИЙ_ПОЯС}), наступний запуск ${task.getNextRun()}`
  );

  return task;
}

module.exports = { startScheduler, РОЗКЛАД, ЧАСОВИЙ_ПОЯС };

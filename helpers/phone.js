// Канонічний вигляд телефону — 12 цифр, що починаються з 380.
//
// Один нормалізатор на весь проєкт. Його потребують ДВІ незалежні речі:
// Нова Пошта (яка відхиляє будь-що, крім цифр) і пошук клієнта CRM за
// телефоном. Два окремі нормалізатори неминуче розійшлись би — і тоді
// замовлення прив'язалось би не до того клієнта, що помітно вже пізно.
//
// ⚠️ На вигляд однакові номери в базі записані по-різному: «+380671234567»,
// «0671234567», «+38 (067) 123-45-67». Рядкове порівняння їх не зведе, тому
// шукати клієнта можна ТІЛЬКИ за нормалізованим значенням.
function normalizePhone(value) {
  const digits = String(value || '').replace(/\D/g, '');

  if (digits.length === 12 && digits.startsWith('380')) {
    return digits;
  }

  if (digits.length === 10 && digits.startsWith('0')) {
    return `38${digits}`;
  }

  if (digits.length === 9) {
    return `380${digits}`;
  }

  // Чужа країна або сміття — віддаємо цифри як є. Краще шукати за неповним
  // ключем, ніж мовчки викинути номер.
  return digits;
}

// Український номер у канонічному записі `+380XXXXXXXXX` — або null.
//
// ⚠️ Дзеркало `phoneSchema.ts` на клієнтському фронті, і навмисно: менеджер
// вводить у адмінці номери з тих самих джерел, що й клієнт у checkout — з
// розмови, з месенджера, вставкою з довідника. Правила мусять збігатись, бо
// інакше номер, який фронт вважає правильним, адмінка відхилить (або навпаки).
//
// ⚠️ Нуль-транк (067…) прибираємо, а не відхиляємо. Це не помилка людини, а
// локальний запис, яким в Україні користуються всі; відхиляти його означало б
// змушувати менеджера робити роботу, яку код робить за рядок.
//
// ⚠️ Перша цифра національної частини не буває нулем у жодного оператора —
// саме так ловиться зайвий нуль, коли номер уже з кодом країни (+380067…).
const UA_PHONE = /^\+380[1-9]\d{8}$/;

function toUaPhone(value) {
  let digits = String(value || '').replace(/\D/g, '');

  if (digits.startsWith('380')) {
    digits = digits.slice(3);
  } else if (digits.startsWith('38')) {
    // Хтось диктує «38 067…» — код країни без плюса.
    digits = digits.slice(2);
  }

  digits = digits.replace(/^0+/, '');

  const phone = `+380${digits}`;

  return UA_PHONE.test(phone) ? phone : null;
}

module.exports = { normalizePhone, toUaPhone };

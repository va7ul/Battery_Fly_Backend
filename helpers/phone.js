// Канонічний вигляд телефону — 12 цифр, що починаються з 380.
//
// Один нормалізатор на весь проєкт. Його потребують ДВІ незалежні речі:
// Нова Пошта (яка відхиляє будь-що, крім цифр) і пошук клієнта CRM за
// телефоном. Два окремі нормалізатори неминуче розійшлись би — і тоді
// замовлення прив'язалось би не до того клієнта, що помітно вже пізно.
//
// ⚠️ На вигляд однакові номери в базі записані по-різному: «+380671234567»,
// «0671234567», «+38 (067) 123-45-67». Рядкове порівняння їх не зведе, тому
// шукати клієнта можна ТІЛЬКИ за нормалізованим значенням.
function normalizePhone(value) {
  const digits = String(value || '').replace(/\D/g, '');

  if (digits.length === 12 && digits.startsWith('380')) {
    return digits;
  }

  if (digits.length === 10 && digits.startsWith('0')) {
    return `38${digits}`;
  }

  if (digits.length === 9) {
    return `380${digits}`;
  }

  // Чужа країна або сміття — віддаємо цифри як є. Краще шукати за неповним
  // ключем, ніж мовчки викинути номер.
  return digits;
}

module.exports = { normalizePhone };

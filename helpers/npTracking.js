const { npPost } = require('./novaposhta');

// Скільки ТТН Пошта приймає за раз.
//
// ⚠️ Не здогадка: перевірено живими запитами. 100 → success, 100 відповідей за
// ~670 мс; 101 → success:false, "Param Documents must not be more than 100 item".
const РОЗМІР_ПАЧКИ = 100;

// ⚠️ Трекінг працює БЕЗ ключа — перевірено живим запитом (apiKey:'' → HTTP 200,
// success:true). Тому свій бойовий ключ сюди не несемо: ліміти на ньому потрібні
// для створення накладних, а не для опитування статусів щогодини.
const БЕЗ_КЛЮЧА = '';

// Що робити з кодом статусу Нової Пошти.
//
// ⚠️ Коди, крім 3 («Номер не знайдено»), узяті з документації Пошти й НЕ
// перевірені на живих посилках — розвідка це чесно зафіксувала. Тому невідомий
// код НЕ ігнорується: він потрапляє в журнал як проміжний, і буде видно, що
// саме Пошта прислала. Таблиця коригується за першими реальними даними.
const ДІЇ = {
  // Отримано (у т.ч. з видачею грошового переказу).
  9: 'delivered',
  10: 'delivered',
  11: 'delivered',

  // Відмова, повернення, припинене зберігання.
  102: 'return',
  103: 'return',
  105: 'return',
  106: 'return',

  // З накладною щось не так.
  2: 'error',
  3: 'error',
};

// Текстові підказки для тих кодів, де формулювання Пошти саме по собі
// незрозуміле менеджеру.
const ПОЯСНЕННЯ = {
  2: 'накладну видалено',
  3: 'номер не знайдено — ТТН помилковий',
  102: 'відмова від отримання, створено повернення',
  103: 'відмова одержувача',
  105: 'припинено зберігання',
  106: 'отримано, створено накладну зворотної доставки',
};

// 'delivered' | 'return' | 'error' | 'log'
function mapStatusToAction(statusCode) {
  const код = Number(statusCode);

  return {
    action: ДІЇ[код] || 'log',
    hint: ПОЯСНЕННЯ[код] || '',
  };
}

function розбитиНаПачки(items, розмір = РОЗМІР_ПАЧКИ) {
  const пачки = [];

  for (let i = 0; i < items.length; i += розмір) {
    пачки.push(items.slice(i, i + розмір));
  }

  return пачки;
}

// Статуси кількох ТТН.
//
// ⚠️ try/catch стоїть НА КОЖНІЙ ПАЧЦІ, а не навколо всього. npPost кидає при
// success:false (Пошта відповідає HTTP 200 навіть на провал), і без цього одна
// зіпсована накладна в одній пачці лишила б без перевірки всі решта — зокрема
// ті, що вже приїхали й чекають на автоперехід.
//
// Повертає лише те, що вдалося дізнатись. Невдалі пачки логуються й
// пропускаються: наступний прохід за годину спробує їх знову.
async function getTrackingBatch(ttnNumbers) {
  const номери = [...new Set((ttnNumbers || []).map(n => String(n || '').trim()).filter(Boolean))];

  if (номери.length === 0) {
    return { statuses: [], failedBatches: 0 };
  }

  const пачки = розбитиНаПачки(номери);
  const statuses = [];
  let failedBatches = 0;

  for (const пачка of пачки) {
    try {
      const дані = await npPost(
        'TrackingDocument',
        'getStatusDocuments',
        {
          Documents: пачка.map(number => ({ DocumentNumber: number, Phone: '' })),
        },
        БЕЗ_КЛЮЧА
      );

      statuses.push(...дані);
    } catch (error) {
      failedBatches += 1;
      console.error(
        `[np-tracking] пачка з ${пачка.length} ТТН не пройшла:`,
        error.message
      );
    }
  }

  return { statuses, failedBatches };
}

module.exports = {
  getTrackingBatch,
  mapStatusToAction,
  розбитиНаПачки,
  РОЗМІР_ПАЧКИ,
};

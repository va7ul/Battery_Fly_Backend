// Воронка продажів: стадії й правило, хто в ній узагалі бере участь.
//
// Живе окремим файлом, бо тим самим правилом користуються ТРИ місця: ендпоінт
// дошки, зміна стадії й разовий скрипт стартових стадій. Якби кожне мало свою
// умову, вони розійшлися б на першій правці — і клієнт, якого скрипт вважає
// учасником, зник би з дошки.

const FUNNEL_STAGES = [
  'new',
  'contacted',
  'proposal',
  'negotiation',
  'won',
  'lost',
];

// Кінцеві стадії. Не глухий кут: із «Відмови» клієнта можна повернути в роботу.
const FINAL_STAGES = ['won', 'lost'];

// Хто у воронці: заведені вручну АБО оптовики — байдуже, звідки з'явились.
//
// ⚠️ Роздрібний клієнт із сайту у воронку НЕ потрапляє. Їх тисячі, вони
// приходять і купують самі, і дошка з ними перетворилась би на другий, гірший
// список клієнтів. Воронка — про тих, з ким ведуть перемовини.
const isInFunnel = contact =>
  Boolean(contact) && (contact.type === 'manual' || contact.kind === 'wholesale');

// Те саме правило мовою запиту до бази.
//
// ⚠️ Мусить збігатися з isInFunnel вище. Дві форми одного правила тримаємо
// поруч саме тому, що розійтись вони можуть лише тут, в одному файлі.
const FUNNEL_QUERY = { $or: [{ type: 'manual' }, { kind: 'wholesale' }] };

// Стадія, з якої клієнт ПОЧИНАЄ, коли вперше потрапляє у воронку.
//
// Той, у кого вже є замовлення, — не лід: він уже купує. Ставити його в
// «Новий лід» означало б наповнити початок дошки людьми, яким нічого не треба
// продавати. Тому наявність замовлень одразу відправляє в «Співпрацюємо».
const startingStage = hasOrders => (hasOrders ? 'won' : 'new');

module.exports = {
  FUNNEL_STAGES,
  FINAL_STAGES,
  FUNNEL_QUERY,
  isInFunnel,
  startingStage,
};

// Воронка продажів: стадії й правило, хто в ній бере участь.
//
// Живе окремим файлом, бо тим самим правилом користується і ендпоінт дошки, і
// зміна стадії, і картка клієнта. Якби кожне місце мало свою умову, вони
// розійшлися б на першій правці — і клієнт зникав би з дошки, лишаючись при
// цьому «учасником» для іншої половини коду.

const FUNNEL_STAGES = [
  'new',
  'contacted',
  'proposal',
  // «Домовились усно, чекаємо перше замовлення». НЕ «вже купує»: той, хто
  // купив, із воронки виходить (див. isPotential). Колонка тримає найгарячіше —
  // тих, хто пообіцяв і ще не заплатив.
  'won',
  // Окремий вхід, не продовження потоку: сюди потрапляють не ліди, а оптовики,
  // які замовкли.
  'reactivation',
  'lost',
];

// Скільки днів мовчання роблять оптовика «сплячим».
//
// До 14 днів людина просто ще не встигла — смикати її означало б набридати.
// Після 60 відносини вважаємо розірваними: дзвінок «ви два місяці тому щось
// купували» не повертає клієнта, а дошка від таких карток забивається назавжди.
const SLEEP_MIN_DAYS = 14;
const SLEEP_MAX_DAYS = 60;

const ДЕНЬ = 24 * 60 * 60 * 1000;

const днівВід = date => {
  const момент = date ? new Date(date).getTime() : NaN;

  return Number.isFinite(момент) ? Math.floor((Date.now() - момент) / ДЕНЬ) : null;
};

// Кандидати на воронку мовою запиту до бази.
//
// ⚠️ Це лише ПЕРШИЙ фільтр. Головна умова — наявність замовлень — живе в іншій
// колекції, тож запитом її не виразити; остаточно відсіює isInFunnel нижче.
const FUNNEL_CANDIDATES = { $or: [{ type: 'manual' }, { kind: 'wholesale' }] };

// Потенційний: заведений вручну або оптовик, який ЩЕ НІЧОГО не купив.
//
// ⚠️ Перше замовлення виводить клієнта з воронки назавжди. Воронка — про те,
// щоб довести людину до першої покупки; той, хто вже купує, живе у списку
// клієнтів, і тримати його на дошці означало б перетворити її на другий,
// гірший список.
const isPotential = (contact, ordersCount) =>
  Boolean(contact) &&
  (contact.type === 'manual' || contact.kind === 'wholesale') &&
  Number(ordersCount) === 0;

// Сплячий: оптовик, який замовкнув на 14–60 днів.
//
// ⚠️ Тільки опт. Роздрібний купує раз на рік за потребою, і «мовчання» в нього
// нічого не означає — дошка зі всіма роздрібними стала б списком усієї бази.
const isSleeping = (contact, lastOrderAt) => {
  if (!contact || contact.kind !== 'wholesale') {
    return false;
  }

  const днів = днівВід(lastOrderAt);

  return днів !== null && днів >= SLEEP_MIN_DAYS && днів <= SLEEP_MAX_DAYS;
};

// Хто на дошці: потенційні + сплячі. Два різні стани, одна відповідь.
const isInFunnel = (contact, { ordersCount = 0, lastOrderAt = null } = {}) =>
  isPotential(contact, ordersCount) || isSleeping(contact, lastOrderAt);

module.exports = {
  FUNNEL_STAGES,
  FUNNEL_CANDIDATES,
  SLEEP_MIN_DAYS,
  SLEEP_MAX_DAYS,
  днівВід,
  isPotential,
  isSleeping,
  isInFunnel,
};
